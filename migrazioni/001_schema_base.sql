-- Schema base del Portale Unico VVF (login, profilo da WAUC, specializzazioni, utenti/settori/permessi, organico, registro).
-- Le funzioni (OCO/SO, NBCR, SAF...) non fanno parte di questa base: verranno aggiunte in seguito con una nuova migrazione.
CREATE TABLE comandi(
  id INTEGER PRIMARY KEY,
  nome TEXT UNIQUE NOT NULL,
  sigla TEXT);
CREATE TABLE utenti(
  id INTEGER PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  nome TEXT,
  cognome TEXT,
  comando_id INTEGER REFERENCES comandi(id),
  is_admin INTEGER NOT NULL DEFAULT 0,
  stato TEXT NOT NULL DEFAULT 'in_attesa' CHECK(stato IN ('in_attesa','attivo','disabilitato')),
  creato_il TEXT,
  ultimo_accesso TEXT,
  approvato_da INTEGER REFERENCES utenti(id),
  approvato_il TEXT,
  matricola TEXT,
  qualifica TEXT,
  distaccamento TEXT,
  telefono TEXT,
  origine_profilo TEXT,
  profilo_confermato INTEGER NOT NULL DEFAULT 0,
  cod_qualifica TEXT,
  cod_gruppo TEXT,
  cod_tipo_personale TEXT,
  tipo_personale TEXT,
  turno TEXT,
  salto_turno TEXT);
CREATE TABLE settori(
  id INTEGER PRIMARY KEY,
  codice TEXT UNIQUE NOT NULL,
  nome TEXT NOT NULL,
  descrizione TEXT);
CREATE TABLE permessi(
  utente_id INTEGER NOT NULL REFERENCES utenti(id) ON DELETE CASCADE,
  settore_id INTEGER NOT NULL REFERENCES settori(id) ON DELETE CASCADE,
  livello TEXT NOT NULL CHECK(livello IN ('lettura','scrittura','gestore')),
  PRIMARY KEY(utente_id, settore_id));
CREATE TABLE audit(
  id INTEGER PRIMARY KEY,
  ts TEXT,
  utente_email TEXT,
  azione TEXT,
  dettaglio TEXT);
CREATE TABLE organico(
  id INTEGER PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  nome TEXT,
  cognome TEXT,
  matricola TEXT,
  qualifica TEXT,
  comando TEXT,
  distaccamento TEXT,
  telefono TEXT,
  importato_il TEXT);
CREATE TABLE specializzazioni_utente(
  utente_id INTEGER NOT NULL REFERENCES utenti(id) ON DELETE CASCADE,
  codice TEXT NOT NULL,
  descrizione TEXT,
  origine TEXT NOT NULL DEFAULT 'wauc',
  inizio TEXT,
  fine TEXT,
  PRIMARY KEY(utente_id, codice));
CREATE TABLE specializzazioni(
  codice TEXT PRIMARY KEY,
  descrizione TEXT,
  aggiornata_il TEXT,
  fonte TEXT NOT NULL DEFAULT 'wauc');
CREATE TABLE anagrafica_wauc(
  utente_id INTEGER PRIMARY KEY REFERENCES utenti(id) ON DELETE CASCADE,
  cognome TEXT,
  nome TEXT,
  account_dipvvf TEXT,
  email_vigilfuoco TEXT,
  cod_qualifica TEXT,
  desc_qualifica TEXT,
  nome_qualifica TEXT,
  cod_settore TEXT,
  cod_gruppo TEXT,
  desc_gruppo TEXT,
  ambito TEXT,
  id_sede TEXT,
  cod_sede TEXT,
  cod_distaccamento TEXT,
  desc_sede TEXT,
  desc_sede_padre TEXT,
  turno TEXT,
  salto_turno TEXT,
  cod_tipo_personale TEXT,
  desc_tipo_personale TEXT,
  ultima_sync TEXT);
CREATE TABLE qualifiche_wauc(
  codice TEXT NOT NULL,
  cod_gruppo TEXT NOT NULL DEFAULT '',
  descrizione TEXT,
  nome TEXT,
  cod_settore TEXT,
  desc_gruppo TEXT,
  ambito TEXT,
  PRIMARY KEY(codice, cod_gruppo));
CREATE TABLE valori_wauc(
  campo TEXT NOT NULL,
  codice TEXT NOT NULL,
  descrizione TEXT,
  PRIMARY KEY(campo, codice));
CREATE TABLE distaccamenti_wauc(
  cod_sede TEXT NOT NULL,
  cod_distaccamento TEXT NOT NULL,
  descrizione TEXT,
  PRIMARY KEY(cod_sede, cod_distaccamento));
CREATE TABLE wauc_sedi(
  codice TEXT PRIMARY KEY,
  n_persone INTEGER,
  verificata_il TEXT);
CREATE TABLE wauc_sync(
  chiave TEXT PRIMARY KEY,
  eseguita_il TEXT);

